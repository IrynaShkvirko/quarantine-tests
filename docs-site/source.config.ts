import { defineConfig, defineDocs } from 'fumadocs-mdx/config';
import { metaSchema, pageSchema } from 'fumadocs-core/source/schema';
import { remarkMermaid } from './lib/remark-mermaid.mjs';

/** User-facing docs, written in content/docs. */
export const docs = defineDocs({
  dir: 'content/docs',
  docs: {
    schema: pageSchema,
    // keeps processed Markdown for "Copy Markdown" and llms.txt
    postprocess: { includeProcessedMarkdown: true },
  },
  meta: { schema: metaSchema },
});

/**
 * Engineering docs: generated by scripts/sync-engineering.mjs from the repo's docs/ folder,
 * which stays the source of truth (agents and plans reference docs/... paths).
 */
export const engineering = defineDocs({
  dir: 'content/engineering',
  docs: {
    schema: pageSchema,
    postprocess: { includeProcessedMarkdown: true },
  },
  meta: { schema: metaSchema },
});

export default defineConfig({
  mdxOptions: {
    remarkPlugins: [remarkMermaid],
    rehypeCodeOptions: {
      themes: { light: 'github-light', dark: 'github-dark' },
      langs: ['js', 'ts', 'tsx', 'python', 'bash', 'json', 'yaml', 'toml', 'sql', 'groovy', 'xml', 'text'],
    },
  },
});
